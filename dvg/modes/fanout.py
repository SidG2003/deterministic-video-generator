"""
Approach B — planner + fan-out.

A planner call lays out the whole film as strict JSON (title, a shared style, and
3-10 scene specs). A shared preamble (dvg.fanout_preamble) freezes the palette and
font sizes. Then each scene is generated by its OWN call as a one-section file
(preamble prepended), checked and rendered like any sectioned scene, and the scene
clips are concatenated in plan order. Scene calls run concurrently (capped by
--max-concurrency); a scene that fails its checks is repaired on its own, without
regenerating the others.

Pipeline per scene: LLM call -> assemble (preamble + code) -> scan_code ->
api_check -> contract (static + runtime) -> render (dvg.parallel_render) -> verify.
"""

